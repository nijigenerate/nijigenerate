// Precision zeros/dots are already supplied by the actual typed number
// formatter. Keep sign, grouped integral digits, fraction and exponent separate.
template<class Spec> std::string formatNumericLayout(std::string_view prefix, std::string_view integral,
    std::string_view fraction, std::string_view suffix, const Spec& spec,
    bool integerPrecision = false, bool special = false) {
    const auto digits = static_cast<std::int64_t>(integral.size());
    const auto group = static_cast<std::int64_t>(spec.groupSize);
    const bool grouping = !special && spec.grouping && digits > 0 && group > 0 && group != INT_MAX - 1;
    auto front = grouping ? (digits - 1) % group + 1 : 0;
    const auto separators = grouping ? (digits - 1) / group : 0;
    const auto visible = static_cast<std::int64_t>(prefix.size() + integral.size() + fraction.size() + suffix.size()) +
        separators;
    auto delta = static_cast<std::int64_t>(spec.width) - visible;
    const bool zero = spec.zero && !special;
    std::string result;
    const auto padding = [&](std::int64_t count, char value) {
        if (count > 0) result.append(static_cast<std::size_t>(count), value);
    };

    if ((!zero || integerPrecision) && delta > 0) {
        if (spec.center) padding(delta / 2 + (delta % 2 && !spec.left ? 1 : 0), ' ');
        else if (!spec.left) padding(delta, ' ');
    }
    result.append(prefix);
    if (zero && !integerPrecision && !spec.left && delta > 0) {
        if (grouping) {
            auto zeroFront = (delta + front - 1) % (group + 1) + 1;
            const auto zeroSeparators = (delta + front - 1) / (group + 1);
            delta -= zeroSeparators;
            // Source POSIX rule: never begin the padded integral part with a separator.
            if (zeroFront > group) zeroFront = 1;
            for (std::int64_t i = 0; i < delta; ++i) {
                if (!zeroFront) { result += formatSeparatorUtf8(spec.separator); zeroFront = group; }
                --zeroFront;
                result.push_back('0');
            }
            if (front == group) result += formatSeparatorUtf8(spec.separator);
        } else padding(delta, '0');
    }
    if (grouping) {
        for (char digit : integral) {
            if (!front) { result += formatSeparatorUtf8(spec.separator); front = group; }
            --front;
            result.push_back(digit);
        }
    } else result.append(integral);
    result.append(fraction);
    result.append(suffix);
    if (delta > 0) {
        if (spec.center) padding(delta / 2 + (delta % 2 && spec.left ? 1 : 0), ' ');
        else if (spec.left) padding(delta, ' ');
    }
    return result;
}

inline std::string formatSeparatorUtf8(char32_t value) {
    if (value > 0x10ffff || (value >= 0xd800 && value <= 0xdfff)) {
        using Text=compat::RetainedString;
        compat::UTFException error(value>0x10ffff
            ?Text::fromStaticLiteral("Encoding an invalid code point in UTF-8")
            :Text::fromStaticLiteral("Encoding a surrogate code point in UTF-8"),
            Text::fromStaticLiteral("std/utf.d"),2311);
        const std::array<std::uint32_t,1> sequence{value}; error.setSequence(sequence);
        throw error;
    }
    try {
        std::string result;
        if (value < 0x80) result.push_back(static_cast<char>(value));
        else if (value < 0x800) {
            result.push_back(static_cast<char>(0xc0 | (value >> 6)));
            result.push_back(static_cast<char>(0x80 | (value & 0x3f)));
        } else if (value < 0x10000) {
            result.push_back(static_cast<char>(0xe0 | (value >> 12)));
            result.push_back(static_cast<char>(0x80 | ((value >> 6) & 0x3f)));
            result.push_back(static_cast<char>(0x80 | (value & 0x3f)));
        } else {
            result.push_back(static_cast<char>(0xf0 | (value >> 18)));
            result.push_back(static_cast<char>(0x80 | ((value >> 12) & 0x3f)));
            result.push_back(static_cast<char>(0x80 | ((value >> 6) & 0x3f)));
            result.push_back(static_cast<char>(0x80 | (value & 0x3f)));
        }
        return result;
    } catch (const std::bad_alloc&) {
        throw compat::ngStaticError<compat::OutOfMemoryError>(std::source_location::current());
    } catch (const std::length_error&) {
        throw compat::ngStaticError<compat::OutOfMemoryError>(std::source_location::current());
    }
}


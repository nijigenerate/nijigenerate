inline std::uint16_t formatControlWord() {
#if defined(_MSC_VER) && defined(_M_X64)
    alignas(16) unsigned char state[512]{};
    _fxsave(state);
    return static_cast<std::uint16_t>(state[0] | (static_cast<unsigned int>(state[1]) << 8));
#elif defined(__i386__) || defined(__x86_64__)
    std::uint16_t word;
    __asm__ __volatile__("fnstcw %0" : "=m"(word));
    return word;
#else
    const int mode = std::fegetround();
    return mode == FE_DOWNWARD ? 0x0400 : mode == FE_UPWARD ? 0x0800
        : mode == FE_TOWARDZERO ? 0x0c00 : 0;
#endif
}

inline int formatRounding() {
    // Phobos FloatingPointControl reads x87, not the CRT/SSE rounding mode.
    switch (formatControlWord() & 0x0c00) {
    case 0x0400: return FE_DOWNWARD;
    case 0x0800: return FE_UPWARD;
    case 0x0c00: return FE_TOWARDZERO;
    default: return FE_TONEAREST;
    }
}

inline std::string floatTextWithMode(float value, int rounding) {
    using boost::multiprecision::cpp_int;
    const auto bits = std::bit_cast<std::uint32_t>(value);
    const bool negative = (bits >> 31) != 0;
    const auto magnitude = bits & 0x7fffffffu;
    const std::string sign = negative ? "-" : "";
    if (magnitude >= 0x7f800000u) {
        return sign + (magnitude == 0x7f800000u ? "inf" : "nan");
    }
    if (magnitude == 0) return sign + "0";
    const auto exponent = magnitude >> 23;
    const auto mantissa = magnitude & 0x7fffffu;
    cpp_int numerator = exponent == 0 ? mantissa : (mantissa | 0x800000u);
    cpp_int denominator = 1;
    const int binaryExponent = exponent == 0 ? -149 : static_cast<int>(exponent) - 150;
    if (binaryExponent >= 0) numerator <<= binaryExponent;
    else denominator <<= -binaryExponent;

    bool useScientific;
    if (rounding == FE_UPWARD || rounding == FE_DOWNWARD) {
        const bool roundAway = rounding == FE_UPWARD ? !negative : negative;
        useScientific = numerator >= denominator * (roundAway ? 999999 : 1000000)
            || (roundAway ? numerator * 10000000000ULL < denominator * 999999
                          : numerator * 10000 < denominator);
    } else if (rounding == FE_TOWARDZERO) {
        useScientific = numerator >= denominator * 1000000 || numerator * 10000 < denominator;
    } else {
        useScientific = numerator * 2 >= denominator * 1999999
            || numerator * 20000000000ULL < denominator * 1999999;
    }

    int decimalExponent = 0;
    while (numerator < denominator) {
        numerator *= 10;
        --decimalExponent;
    }
    while (numerator >= denominator * 10) {
        denominator *= 10;
        ++decimalExponent;
    }
    const cpp_int scaled = numerator * 100000;
    cpp_int digits = scaled / denominator;
    const cpp_int remainder = scaled % denominator;
    bool increment = false;
    if (rounding == FE_UPWARD) increment = !negative && remainder != 0;
    else if (rounding == FE_DOWNWARD) increment = negative && remainder != 0;
    else if (rounding != FE_TOWARDZERO) {
        increment = remainder * 2 > denominator
            || (remainder * 2 == denominator && (digits & 1) != 0);
    }
    if (increment) ++digits;
    if (digits == 1000000) {
        digits /= 10;
        ++decimalExponent;
    }
    auto text = std::to_string(digits.convert_to<std::uint32_t>());
    while (text.size() > 1 && text.back() == '0') text.pop_back();
    if (useScientific) {
        if (text.size() > 1) text.insert(1, ".");
        auto exponentText = std::to_string(decimalExponent < 0 ? -decimalExponent : decimalExponent);
        if (exponentText.size() < 2) exponentText.insert(0, "0");
        return sign + text + (decimalExponent < 0 ? "e-" : "e+") + exponentText;
    }
    const int point = decimalExponent + 1;
    if (point <= 0) return sign + "0." + std::string(static_cast<std::size_t>(-point), '0') + text;
    if (point >= static_cast<int>(text.size())) {
        return sign + text + std::string(static_cast<std::size_t>(point) - text.size(), '0');
    }
    text.insert(static_cast<std::size_t>(point), ".");
    return sign + text;
}

inline std::string floatText(float value) {
    return floatTextWithMode(value, formatRounding());
}

inline std::string vectorText(nicxlive::core::math::Vec2 value) {
    return "[" + floatText(value.x) + ", " + floatText(value.y) + "]";
}

inline void writeLine(const std::string& text) {
    providers::mcp::stdio::standardOutput().writeln(text);
}

inline void begin(nicxlive::core::math::Vec2 a, nicxlive::core::math::Vec2 b,
    nicxlive::core::math::Vec2 c, nicxlive::core::math::Vec2 d) {
    writeLine("in_circle(" + vectorText(a) + ", " + vectorText(b) + ", " + vectorText(c) + ", " + vectorText(d) + ")");
}

inline void determinant(float value) {
    writeLine("det=" + floatText(value));
}


#include "nijigenerate/core/math/triangle_grid.hpp"
#include <cmath>
#include <cstddef>
#include <limits>
#include <span>

namespace nijigenerate::core::math::triangle::detail::grid_deformation {

inline bool axisIsClose(float lhs, float rhs, float maxRelDiff, float maxAbsDiff) {
    if (lhs == rhs) return true;
    const float infinity = std::numeric_limits<float>::infinity();
    if (lhs == infinity || lhs == -infinity) return false;
    if (rhs == infinity || rhs == -infinity) return false;
    const float diff = std::fabs(lhs - rhs);
    return diff <= maxRelDiff * std::fabs(lhs)
        || diff <= maxRelDiff * std::fabs(rhs)
        || diff <= maxAbsDiff;
}

inline bool locateInterval(std::span<const float> axis, float value,
    std::size_t& cell, float& weight) {
    // D initializes both out arguments before entering the function body.
    cell = 0;
    weight = std::numeric_limits<float>::quiet_NaN();
    if (axis.size() < 2) return false;
    constexpr float maxRel = 1e-4f;
    constexpr float maxAbs = 1e-5f;
    if (value <= axis[0]) {
        if (axisIsClose(value, axis[0], maxRel, maxAbs)) {
            cell = 0;
            weight = 0;
            return true;
        }
        return false;
    }
    if (value >= axis[axis.size() - 1]) {
        if (axisIsClose(value, axis[axis.size() - 1], maxRel, maxAbs)) {
            cell = axis.size() - 2;
            weight = 1;
            return true;
        }
        return false;
    }
    for (std::size_t i = 0; i < axis.size() - 1; ++i) {
        const float a = axis[i];
        const float b = axis[i + 1];
        if (value >= a && value <= b) {
            const float span = b - a;
            weight = span > 0 ? (value - a) / span : 0;
            weight = clampValue(weight, 0.0f, 1.0f);
            cell = i;
            return true;
        }
    }
    return false;
}

}

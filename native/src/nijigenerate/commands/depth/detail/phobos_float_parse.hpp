using FloatConvException = compat::PhobosConvException;
using FloatUtfException = compat::UTFException;

inline std::size_t trailingScalarLength(std::string_view input) {
    return compat::phobos::ngUnexpectedScalarLength(input);
}

inline std::int32_t addExponent(std::int32_t left, std::int32_t right) {
    return std::bit_cast<std::int32_t>(static_cast<std::uint32_t>(left) + static_cast<std::uint32_t>(right));
}

inline float parseStringFloat(std::string_view source) try {
    std::size_t position = 0;
    const auto byte = [&]() { return static_cast<unsigned char>(source[position]); };
    const auto lower = [](unsigned char c) { return c >= 'A' && c <= 'Z' ? c + ('a' - 'A') : c; };
    const auto digit = [](unsigned char c) { return c >= '0' && c <= '9'; };
    const auto bail = [&](std::string_view message, std::size_t sourceLine) -> void {
        std::string text(message);
        text += " for input \"";
        if (!source.empty()) text.append(source.data(), source.size());
        text += "\".";
        throw FloatConvException(compat::RetainedString(std::move(text)),
            compat::RetainedString::fromStaticLiteral("std/conv.d"), sourceLine);
    };
    const auto finish = [&](float value) {
        if (position != source.size()) {
            const auto remaining = source.substr(position);
            const auto scalarLength = trailingScalarLength(remaining);
            std::string text = "Unexpected '";
            if (remaining.front() == '\n') text += "\\n";
            else text.append(remaining.data(), scalarLength);
            text += "' when converting from type string to type float";
            throw FloatConvException(compat::RetainedString(std::move(text)),
                compat::RetainedString::fromStaticLiteral("std/conv.d"), 2013);
        }
        return value;
    };
    if (source.empty()) bail("Floating point conversion error", 3164);
    bool negative = false;
    bool parseInfinity = false;
    if (byte() == '-') {
        negative = true;
        ++position;
        if (position == source.size()) bail("Floating point conversion error", 3175);
        parseInfinity = lower(byte()) == 'i';
    } else if (byte() == '+') {
        ++position;
        if (position == source.size()) bail("Floating point conversion error", 3182);
    } else parseInfinity = lower(byte()) == 'i';
    if (parseInfinity) {
        ++position;
        if (position == source.size() || lower(byte()) != 'n')
            bail("error converting input to floating point", 3189);
        ++position;
        if (position == source.size() || lower(byte()) != 'f')
            bail("error converting input to floating point", 3193);
        ++position;
        const auto value = std::numeric_limits<float>::infinity();
        return finish(negative ? -value : value);
    }

    bool hexadecimal = false;
    const bool startsWithZero = byte() == '0';
    if (startsWithZero) {
        ++position;
        if (position == source.size()) return finish(negative ? -0.0f : 0.0f);
        hexadecimal = byte() == 'x' || byte() == 'X';
        if (hexadecimal) ++position;
    } else if (lower(byte()) == 'n') {
        ++position;
        if (position == source.size() || lower(byte()) != 'a')
            bail("error converting input to floating point", 3241);
        ++position;
        if (position == source.size() || lower(byte()) != 'n')
            bail("error converting input to floating point", 3245);
        ++position;
        return finish(std::numeric_limits<float>::quiet_NaN());
    }

    std::uint64_t most = 0, least = 0, scale = 1;
    std::int32_t exponent = 0;
    std::int32_t dot = 0;
    bool sawDigits = hexadecimal ? false : startsWithZero;
    const std::uint32_t base = hexadecimal ? 16 : 10;
    const std::uint64_t scaleMaximum = hexadecimal ? 0x1000000000000000ULL : 10000000000000000000ULL;
    const std::int32_t exponentStep = hexadecimal ? 4 : 1;
    const auto validDigit = [&](unsigned char c) {
        return digit(c) || (hexadecimal && lower(c) >= 'a' && lower(c) <= 'f');
    };
    while (position < source.size()) {
        unsigned char current = byte();
        while (validDigit(current)) {
            sawDigits = true;
            const auto value = digit(current) ? current - '0' : lower(current) - 'a' + 10;
            if (most < (std::numeric_limits<std::uint64_t>::max() - base) / base)
                most = most * base + value;
            else if (scale < scaleMaximum) { least = least * base + value; scale *= base; }
            else exponent = addExponent(exponent, exponentStep);
            exponent = addExponent(exponent, -dot);
            ++position;
            if (position == source.size()) break;
            current = byte();
            if (current == '_') {
                ++position;
                if (position == source.size()) break;
                current = byte();
            }
        }
        if (current == '.' && !dot) {
            ++position;
            dot += exponentStep;
        } else break;
    }
    if (!sawDigits) bail("no digits seen", 3360);
    if (hexadecimal && (position == source.size() || (byte() != 'p' && byte() != 'P')))
        bail("Floating point parsing: exponent is required", 3363);

    if (hexadecimal || (position < source.size() && lower(byte()) == 'e')) {
        ++position;
        if (position == source.size()) throw FloatConvException(
            compat::RetainedString::fromStaticLiteral("Unexpected end of input"),
            compat::RetainedString::fromStaticLiteral("std/conv.d"), 3378);
        bool negativeExponent = false;
        if (byte() == '-' || byte() == '+') { negativeExponent = byte() == '-'; ++position; }
        bool exponentDigits = false;
        std::int32_t parsedExponent = 0;
        while (position < source.size() && digit(byte())) {
            if (parsedExponent < 0x7fffffff / 10 - 10) parsedExponent = parsedExponent * 10 + byte() - '0';
            ++position;
            exponentDigits = true;
        }
        exponent = addExponent(exponent, negativeExponent ? -parsedExponent : parsedExponent);
        if (!exponentDigits) throw FloatConvException(
            compat::RetainedString::fromStaticLiteral("No digits seen."),
            compat::RetainedString::fromStaticLiteral("std/conv.d"), 3400);
    }

#if defined(NG_BONE_PHOBOS_REAL64)
    NativeReal64 value{static_cast<double>(most)};
    if (scale != 1) value = value.multiply({static_cast<double>(scale)}).addInteger(least);
#elif defined(NG_BONE_PHOBOS_WIDE_REAL)
    NativeWideReal value{static_cast<long double>(most)};
    if (scale != 1) value = value.multiply({static_cast<long double>(scale)}).addInteger(least);
#else
    NativeX87Real value{static_cast<long double>(most)};
    if (scale != 1) value = value.multiply({static_cast<long double>(scale)}).addInteger(least);
#endif
    if (hexadecimal) value = value.scaleBinary(exponent);
    else if (value.nonzero()) {
        std::size_t index = 0;
        std::int32_t power = 4096;
        while (exponent > 0) {
            while (exponent >= power) { value = value.multiply(positivePowers[index]); exponent -= power; }
            power >>= 1;
            ++index;
        }
        while (exponent < 0) {
            while (exponent <= -power) {
                value = value.multiply(negativePowers[index]);
                if (!value.nonzero()) throw FloatConvException(
                    compat::RetainedString::fromStaticLiteral("Range error"),
                    compat::RetainedString::fromStaticLiteral("std/conv.d"), 3433);
                exponent += power;
            }
            power >>= 1;
            ++index;
        }
    }
    const auto result = value.toFloat(negative);
    if (!std::isfinite(result)) throw FloatConvException(
        compat::RetainedString::fromStaticLiteral("Range error"),
        compat::RetainedString::fromStaticLiteral("std/conv.d"), 3445);
    return finish(result);
} catch (const std::bad_alloc&) {
    throw compat::ngStaticError<compat::OutOfMemoryError>(
        compat::RetainedString::fromStaticLiteral("rt/lifetime.d"), 1142);
} catch (const std::length_error&) {
    throw compat::ngStaticError<compat::OutOfMemoryError>(
        compat::RetainedString::fromStaticLiteral("rt/lifetime.d"), 1142);
}

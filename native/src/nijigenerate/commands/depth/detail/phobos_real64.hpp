#include <array>
#include <bit>
#include <cstdint>
#include <limits>

namespace nijigenerate::commands::depth::bone::phobos_float_detail {

// LDC's default real is binary64 on MSVC, Darwin AArch64, and its fallback targets.
// This is a target-domain adaptation, not evidence of a reference execution.
static_assert(std::numeric_limits<double>::is_iec559 && std::numeric_limits<double>::radix == 2 &&
    std::numeric_limits<double>::digits == 53 && std::numeric_limits<double>::max_exponent == 1024 &&
    std::numeric_limits<double>::min_exponent == -1021 &&
    std::numeric_limits<float>::is_iec559 && std::numeric_limits<float>::digits == 24 &&
    std::numeric_limits<float>::max_exponent == 128 && std::numeric_limits<float>::min_exponent == -125,
    "The Phobos real64 adapter requires binary64 real and binary32 float");

struct NativeReal64 {
    double value = 0.0;

    bool nonzero() const noexcept { return value != 0.0; }
    NativeReal64 multiply(const NativeReal64& other) const {
        volatile double product = value * other.value;
        return {product};
    }
    NativeReal64 addInteger(std::uint64_t other) const {
        volatile double integer = static_cast<double>(other);
        volatile double sum = value + integer;
        return {sum};
    }
    NativeReal64 scaleBinary(std::int32_t power) const {
        // Preserve the selected LDC core.math.ldexpImpl operation, including
        // its bit-truncated subnormal output rather than libc rounding/errno.
        constexpr std::uint64_t sign = std::uint64_t{1} << 63;
        constexpr std::uint64_t exponentMask = std::uint64_t{0x7ff} << 52;
        constexpr std::uint64_t mantissaMask = (std::uint64_t{1} << 52) - 1;
        auto bits = std::bit_cast<std::uint64_t>(value);
        auto exponent = static_cast<std::int32_t>((bits & exponentMask) >> 52);
        if (exponent == 0x7ff) return *this;
        if (exponent == 0) {
            volatile double normalized = value * 0x1p52;
            bits = std::bit_cast<std::uint64_t>(static_cast<double>(normalized));
            exponent = static_cast<std::int32_t>((bits & exponentMask) >> 52) - 52;
        }
        const auto sum = static_cast<std::int64_t>(power) + exponent;
        const bool overflow = sum < std::numeric_limits<std::int32_t>::min() ||
            sum > std::numeric_limits<std::int32_t>::max();
        if (overflow || sum >= 0x7ff) {
            bits = (bits & sign) ^ exponentMask;
        } else if (sum > 0) {
            bits = (bits & ~exponentMask) ^ (static_cast<std::uint64_t>(sum) << 52);
        } else {
            const auto displacement = 1 - sum;
            const auto shift = static_cast<unsigned>(displacement > 53 ? 53 : displacement);
            const auto mantissa = (bits & mantissaMask) ^ (std::uint64_t{1} << 52);
            bits = (bits & sign) ^ (mantissa >> shift);
        }
        return {std::bit_cast<double>(bits)};
    }
    float toFloat(bool negative) const {
        return static_cast<float>(negative ? -value : value);
    }
};

// Same real literals and order as std.conv, rounded to this target's real.
// 10^+512 and larger overflow binary64; 10^-512 and smaller underflow to zero.
inline constexpr std::array<NativeReal64, 14> negativePowers{{
    {0.0}, {0.0}, {0.0}, {0.0}, {1e-256}, {1e-128}, {1e-64},
    {1e-32}, {1e-16}, {1e-8}, {1e-4}, {1e-2}, {1e-1}, {1.0}
}};
inline constexpr std::array<NativeReal64, 13> positivePowers{{
    {std::numeric_limits<double>::infinity()},
    {std::numeric_limits<double>::infinity()},
    {std::numeric_limits<double>::infinity()},
    {std::numeric_limits<double>::infinity()},
    {1e256}, {1e128}, {1e64}, {1e32}, {1e16}, {1e8}, {1e4}, {1e2}, {1e1}
}};

} // namespace nijigenerate::commands::depth::bone::phobos_float_detail

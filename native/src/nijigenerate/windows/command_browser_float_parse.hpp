template<class Allocate> auto allocateParserMemory(Allocate allocate) {
    try {
        return allocate();
    } catch (const std::bad_alloc&) {
        throw compat::ngStaticError<compat::OutOfMemoryError>();
    } catch (const std::length_error&) {
        throw compat::ngStaticError<compat::OutOfMemoryError>();
    }
}

class FloatConvException : public compat::ThrowableException {
public:
    explicit FloatConvException(std::string text,
        const std::source_location where = std::source_location::current())
        : ThrowableException(
            allocateParserMemory([&] { return compat::RetainedString(std::move(text)); }),
            allocateParserMemory([&] { return compat::RetainedString(std::string(where.file_name())); }),
            where.line()) {}
    explicit FloatConvException(const char* text,
        const std::source_location where = std::source_location::current())
        : FloatConvException(allocateParserMemory([&] { return std::string(text); }), where) {}
    std::string_view ngThrowableTypeName() const noexcept override { return "std.conv.ConvException"; }
};

class FloatUtfException : public compat::ThrowableException {
public:
    static std::size_t sequenceLength(std::string_view input) {
        std::size_t length = 1;
        while (length < input.size() && length < 4 &&
            (static_cast<unsigned char>(input[length]) & 0xc0u) == 0x80u) ++length;
        return length;
    }
    static compat::RetainedString sequenceMessage(std::string_view text, std::string_view input) {
        const auto length = sequenceLength(input);
        return allocateParserMemory([&] {
            return compat::RetainedString(std::string(text) + " (at index " + std::to_string(length) + ")");
        });
    }
    std::array<std::uint32_t, 4> sequence{};
    std::size_t len = 0;
    std::size_t idx = 0;
    FloatUtfException(std::string_view text, std::string_view input,
        const std::source_location where = std::source_location::current())
        : ThrowableException(sequenceMessage(text, input),
            allocateParserMemory([&] { return compat::RetainedString(std::string(where.file_name())); }),
            where.line()) {
        len = sequenceLength(input);
        for (std::size_t i = 0; i < len; ++i) sequence[i] = static_cast<unsigned char>(input[i]);
        idx = len;
    }
    std::string_view ngThrowableTypeName() const noexcept override { return "std.utf.UTFException"; }
    compat::RetainedString toString() const override {
        return allocateParserMemory([&] {
            std::string result = "Invalid UTF sequence:";
            constexpr char digits[] = "0123456789abcdef";
            for (std::size_t i = 0; i < len; ++i) {
                result += ' ';
                result += digits[(sequence[i] >> 4) & 15];
                result += digits[sequence[i] & 15];
                result += 'x';
            }
            if (!msg.empty()) { result += " - "; result.append(msg.view()); }
            return compat::RetainedString(std::move(result));
        });
    }
};

inline std::size_t trailingScalarLength(std::string_view input) {
    auto first = static_cast<std::uint8_t>(input.front());
    if (first < 0x80) return 1;
    const auto fail = [&](bool ended) -> void {
        throw FloatUtfException(ended ? "Attempted to decode past the end of a string"
            : "Invalid UTF-8 sequence", input);
    };
    if ((first & 0xc0) != 0xc0) fail(false);
    std::uint32_t scalar = first;
    first = static_cast<std::uint8_t>(first << 1);
    constexpr std::uint32_t masks[] = {0x7f, 0x7ff, 0xffff, 0x1fffff};
    for (std::size_t i = 1; i <= 3; ++i) {
        if (i == input.size()) fail(true);
        const auto next = static_cast<std::uint8_t>(input[i]);
        if ((next & 0xc0) != 0x80) fail(false);
        scalar = (scalar << 6) | (next & 0x3f);
        first = static_cast<std::uint8_t>(first << 1);
        if (!(first & 0x80)) {
            scalar &= masks[i];
            if ((scalar & ~masks[i - 1]) == 0) fail(false);
            if (i == 2 && scalar >= 0xd800 && scalar <= 0xdfff) fail(false);
            if (i == 3 && scalar > 0x10ffff) fail(false);
            return i + 1;
        }
    }
    fail(false);
    return 0;
}

inline std::int32_t addExponent(std::int32_t left, std::int32_t right) {
    return std::bit_cast<std::int32_t>(static_cast<std::uint32_t>(left) + static_cast<std::uint32_t>(right));
}

template<std::floating_point Target> Target parseStringFloat(std::string_view source) {
    std::size_t position = 0;
    const auto byte = [&]() { return static_cast<unsigned char>(source[position]); };
    const auto lower = [](unsigned char c) { return c >= 'A' && c <= 'Z' ? c + ('a' - 'A') : c; };
    const auto digit = [](unsigned char c) { return c >= '0' && c <= '9'; };
    const auto bail = [&](std::string_view message,
        const std::source_location where = std::source_location::current()) -> void {
        auto text = allocateParserMemory([&] {
            std::string result(message);
            result += " for input \"";
            if (!source.empty()) result.append(source.data(), source.size());
            result += "\".";
            return result;
        });
        throw FloatConvException(std::move(text), where);
    };
    const auto finish = [&](Target value) {
        if (position != source.size()) {
            const auto remaining = source.substr(position);
            const auto scalarLength = trailingScalarLength(remaining);
            auto text = allocateParserMemory([&] {
                std::string result = "Unexpected '";
                if (remaining.front() == '\n') result += "\\n";
                else result.append(remaining.data(), scalarLength);
                result += "' when converting from type string to type " +
                    std::string(std::same_as<Target, float> ? "float" : "double");
                return result;
            });
            throw FloatConvException(std::move(text));
        }
        return value;
    };
    if (source.empty()) bail("Floating point conversion error");
    bool negative = false;
    bool parseInfinity = false;
    if (byte() == '-') {
        negative = true;
        ++position;
        if (position == source.size()) bail("Floating point conversion error");
        parseInfinity = lower(byte()) == 'i';
    } else if (byte() == '+') {
        ++position;
        if (position == source.size()) bail("Floating point conversion error");
    } else parseInfinity = lower(byte()) == 'i';
    if (parseInfinity) {
        ++position;
        if (position == source.size() || lower(byte()) != 'n') bail("error converting input to floating point");
        ++position;
        if (position == source.size() || lower(byte()) != 'f') bail("error converting input to floating point");
        ++position;
        const auto value = std::numeric_limits<Target>::infinity();
        return finish(negative ? -value : value);
    }

    bool hexadecimal = false;
    const bool startsWithZero = byte() == '0';
    if (startsWithZero) {
        ++position;
        if (position == source.size()) return finish(negative ? -Target(0) : Target(0));
        hexadecimal = byte() == 'x' || byte() == 'X';
        if (hexadecimal) ++position;
    } else if (lower(byte()) == 'n') {
        ++position;
        if (position == source.size() || lower(byte()) != 'a') bail("error converting input to floating point");
        ++position;
        if (position == source.size() || lower(byte()) != 'n') bail("error converting input to floating point");
        ++position;
        return finish(std::numeric_limits<Target>::quiet_NaN());
    }

    std::uint64_t most = 0, least = 0, scale = 1;
    std::int32_t exponent = 0;
    std::int32_t dot = 0;
    bool sawDigits = hexadecimal ? false : startsWithZero;
    const std::uint32_t base = hexadecimal ? 16 : 10;
    const std::uint64_t scaleMaximum = hexadecimal ? 0x1000000000000000ULL : 10000000000000000000ULL;
    const std::int32_t exponentStep = hexadecimal ? 4 : 1;
    const auto validDigit = [&](unsigned char c) {
        return digit(c) || (hexadecimal && lower(c) >= 'a' && lower(c) <= 'f');
    };
    while (position < source.size()) {
        unsigned char current = byte();
        while (validDigit(current)) {
            sawDigits = true;
            const auto value = digit(current) ? current - '0' : lower(current) - 'a' + 10;
            if (most < (std::numeric_limits<std::uint64_t>::max() - base) / base)
                most = most * base + value;
            else if (scale < scaleMaximum) { least = least * base + value; scale *= base; }
            else exponent = addExponent(exponent, exponentStep);
            exponent = addExponent(exponent, -dot);
            ++position;
            if (position == source.size()) break;
            current = byte();
            if (current == '_') {
                ++position;
                if (position == source.size()) break;
                current = byte();
            }
        }
        if (current == '.' && !dot) {
            ++position;
            dot += exponentStep;
        } else break;
    }
    if (!sawDigits) bail("no digits seen");
    if (hexadecimal && (position == source.size() || (byte() != 'p' && byte() != 'P')))
        bail("Floating point parsing: exponent is required");

    if (hexadecimal || (position < source.size() && lower(byte()) == 'e')) {
        ++position;
        if (position == source.size()) throw FloatConvException("Unexpected end of input");
        bool negativeExponent = false;
        if (byte() == '-' || byte() == '+') { negativeExponent = byte() == '-'; ++position; }
        bool exponentDigits = false;
        std::int32_t parsedExponent = 0;
        while (position < source.size() && digit(byte())) {
            if (parsedExponent < 0x7fffffff / 10 - 10) parsedExponent = parsedExponent * 10 + byte() - '0';
            ++position;
            exponentDigits = true;
        }
        exponent = addExponent(exponent, negativeExponent ? -parsedExponent : parsedExponent);
        if (!exponentDigits) throw FloatConvException("No digits seen.");
    }

    constexpr double inf = std::numeric_limits<double>::infinity();
    constexpr double positivePowers[] = {inf,inf,inf,inf,1e256,1e128,1e64,1e32,1e16,1e8,1e4,1e2,1e1};
    constexpr double negativePowers[] = {0,0,0,0,1e-256,1e-128,1e-64,1e-32,1e-16,1e-8,1e-4,1e-2,1e-1,1};
    double value = static_cast<double>(most);
    if (scale != 1) value = value * static_cast<double>(scale) + static_cast<double>(least);
    if (hexadecimal) value = std::ldexp(value, exponent);
    else if ((value != 0)) {
        std::size_t index = 0;
        std::int32_t power = 4096;
        while (exponent > 0) {
            while (exponent >= power) { value = value * positivePowers[index]; exponent -= power; }
            power >>= 1;
            ++index;
        }
        while (exponent < 0) {
            while (exponent <= -power) {
                value = value * negativePowers[index];
                if (!(value != 0)) throw FloatConvException("Range error");
                exponent += power;
            }
            power >>= 1;
            ++index;
        }
    }
    const auto result = static_cast<Target>(negative ? -value : value);
    if (!std::isfinite(result)) throw FloatConvException("Range error");
    return finish(result);
}

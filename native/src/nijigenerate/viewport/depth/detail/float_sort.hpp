// Like D AssertError, this is outside ordinary std::exception handlers.
struct DepthFloatSortAssertionError {};
#ifndef NDEBUG
#define NG_DEPTH_SORT_ASSERT(condition) do { if (!(condition)) throw DepthFloatSortAssertionError{}; } while (false)
#else
#define NG_DEPTH_SORT_ASSERT(condition) ((void)0)
#endif

inline void sortFloatThree(std::span<float> r, std::size_t a, std::size_t b, std::size_t c) {
    if (r[c] < r[a]) {
        if (r[a] < r[b]) { std::swap(r[a],r[b]); std::swap(r[a],r[c]); }
        else { std::swap(r[a],r[c]); if (r[b] < r[a]) std::swap(r[a],r[b]); }
    } else if (r[b] < r[a]) std::swap(r[a],r[b]);
    else if (r[c] < r[b]) std::swap(r[b],r[c]);
}

inline void sortFloatFive(std::span<float> r) {
    if (r[1] < r[0]) std::swap(r[0],r[1]);
    if (r[3] < r[2]) std::swap(r[2],r[3]);
    if (r[3] < r[1]) { std::swap(r[0],r[2]); std::swap(r[1],r[3]); }
    NG_DEPTH_SORT_ASSERT(!(r[1]<r[0]) && !(r[3]<r[1]) && !(r[3]<r[2]));
    if (r[4] < r[1]) {
        std::swap(r[3],r[4]); std::swap(r[1],r[3]);
        if (r[1] < r[0]) std::swap(r[0],r[1]);
    } else if (r[4] < r[3]) std::swap(r[3],r[4]);
    NG_DEPTH_SORT_ASSERT(!(r[1]<r[0]) && !(r[3]<r[1]) && !(r[4]<r[3]));
    NG_DEPTH_SORT_ASSERT(!(r[4]<r[2]));
    if (r[2] < r[1]) {
        std::swap(r[1],r[2]); if (r[1] < r[0]) std::swap(r[0],r[1]);
    } else if (r[3] < r[2]) std::swap(r[2],r[3]);
}

inline void shortSortFloat(std::span<float> r) {
    switch (r.size()) {
    case 0: case 1: return;
    case 2: if (r[1]<r[0]) std::swap(r[0],r[1]); return;
    case 3: sortFloatThree(r,0,1,2); return;
    case 4:
        if (r[1]<r[0]) std::swap(r[0],r[1]);
        if (r[3]<r[2]) std::swap(r[2],r[3]);
        if (r[2]<r[0]) std::swap(r[0],r[2]);
        if (r[3]<r[1]) std::swap(r[1],r[3]);
        if (r[2]<r[1]) std::swap(r[1],r[2]);
        return;
    default: sortFloatFive(r.last(5)); if (r.size()==5) return;
    }
    for (std::size_t i=r.size()-6;;--i) {
        std::size_t j=i+1;
        const float temp=r[i];
        if (r[j]<temp) {
            do { r[j-1]=r[j]; ++j; } while (j<r.size() && r[j]<temp);
            r[j-1]=temp;
        }
        if (i==0) break;
    }
}

inline std::size_t floatSortPivot(std::span<float> r) {
    const auto mid=r.size()/2;
    if (r.size()<512) {
        if (r.size()>=32) {
            sortFloatThree(r,0,mid,r.size()-1);
            NG_DEPTH_SORT_ASSERT(!(r[mid]<r[0]) && !(r[r.size()-1]<r[mid]));
        }
        return mid;
    }
    const std::size_t a=0,b=mid-r.size()/4,c=mid,d=mid+r.size()/4,e=r.size()-1;
    if (r[c]<r[a]) std::swap(r[a],r[c]);
    if (r[d]<r[b]) std::swap(r[b],r[d]);
    if (r[d]<r[c]) { std::swap(r[c],r[d]); std::swap(r[a],r[b]); }
    if (r[e]<r[b]) std::swap(r[b],r[e]);
    if (r[e]<r[c]) { std::swap(r[c],r[e]); if (r[c]<r[a]) std::swap(r[a],r[c]); }
    else if (r[c]<r[b]) std::swap(r[b],r[c]);
    return mid;
}

inline void siftFloatDown(std::span<float> r,std::size_t parent,std::size_t end) {
    for (;;) {
        auto child=(parent+1)*2;
        if (child>=end) {
            if (child==end && r[parent]<r[--child]) std::swap(r[parent],r[child]);
            break;
        }
        if (r[child]<r[child-1]) --child;
        if (!(r[parent]<r[child])) break;
        std::swap(r[parent],r[child]); parent=child;
    }
}

inline void heapSortFloat(std::span<float> r) {
    if (r.size()<2) return;
    for (std::size_t i=r.size()/2;i-- >0;) siftFloatDown(r,i,r.size());
#ifndef NDEBUG
    std::size_t parent=0;
    for (std::size_t child=1;child<r.size();++child) {
        NG_DEPTH_SORT_ASSERT(!(r[parent]<r[child])); parent+=!(child&1);
    }
#endif
    for (std::size_t end=r.size()-1;end>0;--end) {
        std::swap(r[0],r[end]);
        std::size_t root=0,current=0;
        for (;;) {
            auto child=(current+1)*2;
            if (child>=end) {
                if (child==end) { --child; std::swap(r[current],r[child]); current=child; }
                break;
            }
            if (r[child]<r[child-1]) --child;
            std::swap(r[current],r[child]); current=child;
        }
        for (auto child=current;child>root;child=current) {
            current=(child-1)/2;
            if (!(r[current]<r[child])) break;
            std::swap(r[current],r[child]);
        }
    }
}

inline void quickSortFloat(std::span<float> r,std::size_t depth) {
    while (r.size()>256) {
        if (depth==0) { heapSortFloat(r); return; }
        depth=depth>=std::numeric_limits<std::size_t>::max()/2 ? (depth/3)*2 : (depth*2)/3;
        const auto pivotIndex=floatSortPivot(r);
        const float pivot=r[pivotIndex];
        std::swap(r[pivotIndex],r[r.size()-1]);
        std::size_t left=std::numeric_limits<std::size_t>::max(),right=r.size()-1;
        for (;;) {
            while (r[++left]<pivot) {}
            NG_DEPTH_SORT_ASSERT(left<=right);
            while (right!=left && pivot<r[--right]) {}
            if (right==left) break;
            NG_DEPTH_SORT_ASSERT(left<=right);
            std::swap(r[left],r[right]);
        }
        std::swap(r[r.size()-1],r[left]);
        auto a=r.first(left),b=r.subspan(left+1);
        if (b.size()>a.size()) std::swap(a,b);
        quickSortFloat(b,depth); r=a;
    }
    shortSortFloat(r);
}

inline compat::Slice<float> sortedUniqueFloats(compat::Slice<float> values) {
    const std::span<float> data{values.data(),values.size()};
    compat::phobos_float_sort::sort(data);
    compat::Slice<float> result;
    for (float value:values) if (result.empty() || result[result.size()-1]!=value) result.append(value);
    return result;
}


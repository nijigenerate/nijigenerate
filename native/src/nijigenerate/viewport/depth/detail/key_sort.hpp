// Retained only as a legacy native diagnostic type, not a source Error.
struct DepthKeySortAssertionError {};
#ifndef NDEBUG
#define NG_DEPTH_KEY_SORT_ASSERT(condition, message, line) do { if (!(condition)) \
    throw compat::ngStaticError<compat::AssertError>(compat::RetainedString::fromStaticLiteral(message), \
        compat::RetainedString::fromStaticLiteral("std/algorithm/sorting.d"), line); } while (false)
#else
#define NG_DEPTH_KEY_SORT_ASSERT(condition, message, line) ((void)0)
#endif

template<std::size_t SourceElementBytes,class T,class Less> class SourceKeySorter {
    static_assert(SourceElementBytes>0);
    Less less;
    compat::RetainedString rangeTypeName_;
inline void sortFloatThree(std::span<T> r, std::size_t a, std::size_t b, std::size_t c) {
    if (less(r[c],r[a])) {
        if (less(r[a],r[b])) { std::swap(r[a],r[b]); std::swap(r[a],r[c]); }
        else { std::swap(r[a],r[c]); if (less(r[b],r[a])) std::swap(r[a],r[b]); }
    } else if (less(r[b],r[a])) std::swap(r[a],r[b]);
    else if (less(r[c],r[b])) std::swap(r[b],r[c]);
}

inline void sortFloatFive(std::span<T> r) {
    NG_DEPTH_KEY_SORT_ASSERT(r.size() >= 5, "r must have more than 4 elements", 1807);
    if (less(r[1],r[0])) std::swap(r[0],r[1]);
    if (less(r[3],r[2])) std::swap(r[2],r[3]);
    if (less(r[3],r[1])) { std::swap(r[0],r[2]); std::swap(r[1],r[3]); }
    NG_DEPTH_KEY_SORT_ASSERT(!(less(r[1],r[0])) && !(less(r[3],r[1])) && !(less(r[3],r[2])),
        "unexpected order", 1821);
    if (less(r[4],r[1])) {
        std::swap(r[3],r[4]); std::swap(r[1],r[3]);
        if (less(r[1],r[0])) std::swap(r[0],r[1]);
    } else if (less(r[4],r[3])) std::swap(r[3],r[4]);
    NG_DEPTH_KEY_SORT_ASSERT(!(less(r[1],r[0])) && !(less(r[3],r[1])) && !(less(r[4],r[3])),
        "unexpected order", 1838);
    NG_DEPTH_KEY_SORT_ASSERT(!(less(r[4],r[2])), "unexpected order", 1842);
    if (less(r[2],r[1])) {
        std::swap(r[1],r[2]); if (less(r[1],r[0])) std::swap(r[0],r[1]);
    } else if (less(r[3],r[2])) std::swap(r[2],r[3]);
}

inline void shortSortFloat(std::span<T> r) {
    switch (r.size()) {
    case 0: case 1: return;
    case 2: if (less(r[1],r[0])) std::swap(r[0],r[1]); return;
    case 3: sortFloatThree(r,0,1,2); return;
    case 4:
        if (less(r[1],r[0])) std::swap(r[0],r[1]);
        if (less(r[3],r[2])) std::swap(r[2],r[3]);
        if (less(r[2],r[0])) std::swap(r[0],r[2]);
        if (less(r[3],r[1])) std::swap(r[1],r[3]);
        if (less(r[2],r[1])) std::swap(r[1],r[2]);
        return;
    default: sortFloatFive(r.last(5)); if (r.size()==5) return;
    }
    NG_DEPTH_KEY_SORT_ASSERT(r.size() >= 6, "r must have more than 5 elements", 1729);
    for (std::size_t i=r.size()-6;;--i) {
        if constexpr (std::is_nothrow_invocable_v<Less&, T, T>) {
            std::size_t j=i+1;
            const T temp=r[i];
            if (less(r[j],temp)) {
                do { r[j-1]=r[j]; ++j; } while (j<r.size() && less(r[j],temp));
                r[j-1]=temp;
            }
        } else {
            std::size_t j=i;
            while (less(r[j+1],r[j])) {
                std::swap(r[j],r[j+1]);
                if (j==r.size()-2) break;
                ++j;
            }
        }
        if (i==0) break;
    }
}

inline std::size_t floatSortPivot(std::span<T> r) {
    const auto mid=r.size()/2;
    if (r.size()<512) {
        if (r.size()>=32) {
            NG_DEPTH_KEY_SORT_ASSERT(r.size() >= 3,
                "r.length must be greater than or equal to Indexes.length", 4349);
            NG_DEPTH_KEY_SORT_ASSERT(0 != mid, "a != b ", 4365);
            NG_DEPTH_KEY_SORT_ASSERT(0 != r.size()-1 && mid != r.size()-1, "a != c && b != c", 4372);
            sortFloatThree(r,0,mid,r.size()-1);
            NG_DEPTH_KEY_SORT_ASSERT(!(less(r[mid],r[0])), "less than check failed", 4420);
            NG_DEPTH_KEY_SORT_ASSERT(!(less(r[r.size()-1],r[mid])), "less than check failed", 4421);
        }
        return mid;
    }
    const std::size_t a=0,b=mid-r.size()/4,c=mid,d=mid+r.size()/4,e=r.size()-1;
    NG_DEPTH_KEY_SORT_ASSERT(r.size() >= 5,
        "r.length must be greater than or equal to Indexes.length", 4349);
    NG_DEPTH_KEY_SORT_ASSERT(a != b, "a != b ", 4365);
    NG_DEPTH_KEY_SORT_ASSERT(a != c && b != c, "a != c && b != c", 4372);
    NG_DEPTH_KEY_SORT_ASSERT(a != d && b != d && c != d, "a != d && b != d && c != d failed", 4379);
    NG_DEPTH_KEY_SORT_ASSERT(a != e && b != e && c != e && d != e,
        "a != e && b != e && c != e && d != e failed", 4386);
    if (less(r[c],r[a])) std::swap(r[a],r[c]);
    if (less(r[d],r[b])) std::swap(r[b],r[d]);
    if (less(r[d],r[c])) { std::swap(r[c],r[d]); std::swap(r[a],r[b]); }
    if (less(r[e],r[b])) std::swap(r[b],r[e]);
    if (less(r[e],r[c])) { std::swap(r[c],r[e]); if (less(r[c],r[a])) std::swap(r[a],r[c]); }
    else if (less(r[c],r[b])) std::swap(r[b],r[c]);
    return mid;
}

inline void siftFloatDown(std::span<T> r,std::size_t parent,std::size_t end) {
    for (;;) {
        auto child=(parent+1)*2;
        if (child>=end) {
            if (child==end && less(r[parent],r[--child])) std::swap(r[parent],r[child]);
            break;
        }
        if (less(r[child],r[child-1])) --child;
        if (!(less(r[parent],r[child]))) break;
        std::swap(r[parent],r[child]); parent=child;
    }
}

inline void heapSortFloat(std::span<T> r) {
    if (r.size()<2) return;
    for (std::size_t i=r.size()/2;i-- >0;) siftFloatDown(r,i,r.size());
#ifndef NDEBUG
    std::size_t parent=0;
    for (std::size_t child=1;child<r.size();++child) {
        NG_DEPTH_KEY_SORT_ASSERT(!(less(r[parent],r[child])), "r is not a heap", 2258); parent+=!(child&1);
    }
#endif
    for (std::size_t end=r.size()-1;end>0;--end) {
        std::swap(r[0],r[end]);
        std::size_t root=0,current=0;
        for (;;) {
            auto child=(current+1)*2;
            if (child>=end) {
                if (child==end) { --child; std::swap(r[current],r[child]); current=child; }
                break;
            }
            if (less(r[child],r[child-1])) --child;
            std::swap(r[current],r[child]); current=child;
        }
        for (auto child=current;child>root;child=current) {
            current=(child-1)/2;
            if (!(less(r[current],r[child]))) break;
            std::swap(r[current],r[child]);
        }
    }
}

inline void quickSortFloat(std::span<T> r,std::size_t depth) {
    constexpr auto shortSortGetsBetter=std::size_t{1024}/SourceElementBytes>32
        ?std::size_t{1024}/SourceElementBytes:std::size_t{32};
    while (r.size()>shortSortGetsBetter) {
        if (depth==0) { heapSortFloat(r); return; }
        depth=depth>=std::numeric_limits<std::size_t>::max()/2 ? (depth/3)*2 : (depth*2)/3;
        const auto pivotIndex=floatSortPivot(r);
        const T pivot=r[pivotIndex];
        std::swap(r[pivotIndex],r[r.size()-1]);
        std::size_t left=std::numeric_limits<std::size_t>::max(),right=r.size()-1;
        for (;;) {
            while (less(r[++left],pivot)) {}
            NG_DEPTH_KEY_SORT_ASSERT(left<=right, "sort: invalid comparison function.", 2195);
            while (right!=left && less(pivot,r[--right])) {}
            if (right==left) break;
            NG_DEPTH_KEY_SORT_ASSERT(left<=right, "sort: invalid comparison function.", 2201);
            std::swap(r[left],r[right]);
        }
        std::swap(r[r.size()-1],r[left]);
        auto a=r.first(left),b=r.subspan(left+1);
        if (b.size()>a.size()) std::swap(a,b);
        quickSortFloat(b,depth); r=a;
    }
    shortSortFloat(r);
}


public:
    SourceKeySorter(Less predicate, compat::RetainedString rangeTypeName)
        :less(std::move(predicate)),rangeTypeName_(std::move(rangeTypeName)) {}
    void sort(compat::Slice<T> values) {
        std::span<T> data{values.data(),values.size()};
        quickSortFloat(data,data.size());
#ifndef NDEBUG
        for (std::size_t i=1;i<data.size();++i) {
            if (!less(data[i],data[i-1])) continue;
            NG_DEPTH_KEY_SORT_ASSERT(!less(data[i-1],data[i]),
                "Predicate for isSorted is not antisymmetric. Both"
                " pred(a, b) and pred(b, a) are true for certain values.", 179);
            std::string message = "Failed to sort range of type ";
            message += rangeTypeName_.view();
            throw compat::ngStaticError<compat::AssertError>(compat::RetainedString(std::move(message)),
                compat::RetainedString::fromStaticLiteral("std/algorithm/sorting.d"), 1973);
        }
#endif
    }
};

template<std::size_t SourceElementBytes,class T,class Less> void sortBy(compat::Slice<T> values,Less predicate,
    compat::RetainedString rangeTypeName) {
    SourceKeySorter<SourceElementBytes,T,Less>{std::move(predicate),std::move(rangeTypeName)}.sort(values);
}


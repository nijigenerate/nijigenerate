#include <bit>
#include <cmath>
#include <cstdint>
#include <limits>

namespace nijigenerate::compat::phobos_exp_float {

// expImpl's reduced polynomial is positive and normal; only this scaling
// domain of LDC core.math.ldexp is required. Its subnormal truncation is kept.
inline float scaleReduced(float value, int power) {
    auto bits = std::bit_cast<std::uint32_t>(value);
    const int exponent = static_cast<int>((bits >> 23) & 0xffu) + power;
    if (exponent >= 255) {
        bits = (bits & 0x80000000u) ^ 0x7f800000u;
    } else if (exponent > 0) {
        bits = (bits & ~0x7f800000u) ^ (static_cast<std::uint32_t>(exponent) << 23);
    } else {
        int shift = 1 - exponent;
        if (shift > 24) shift = 24;
        const auto mantissa = (bits & 0x007fffffu) ^ 0x00800000u;
        bits = (bits & 0x80000000u) ^ (mantissa >> shift);
    }
    return std::bit_cast<float>(bits);
}

inline float exp(float x) {
    static_assert(sizeof(float) == 4 && std::numeric_limits<float>::is_iec559
                  && std::numeric_limits<float>::digits == 24);
    constexpr float coefficients[]{5.0000001201E-1f, 1.6666665459E-1f,
        4.1665795894E-2f, 8.3334519073E-3f, 1.3981999507E-3f, 1.9875691500E-4f};
    constexpr float c1 = 0.693359375f;
    constexpr float c2 = -2.12194440e-4f;
    constexpr float overflow = 88.72283905206835f;
    constexpr float underflow = -103.278929903431851103f;
    constexpr float log2e = 0x1.715476p+0f;
    if (std::isnan(x)) return x;
    if (x > overflow) return std::numeric_limits<float>::infinity();
    if (x < underflow) return 0.0f;

    float xx = std::floor(log2e * x + 0.5f);
    const int power = static_cast<int>(xx);
    x -= xx * c1;
    x -= xx * c2;
    xx = x * x;
    float polynomial = coefficients[5];
    for (int i = 4; i >= 0; --i) {
        polynomial *= x;
        polynomial += coefficients[i];
    }
    x = polynomial * xx + x + 1.0f;
    return scaleReduced(x, power);
}

} // namespace nijigenerate::compat::phobos_exp_float

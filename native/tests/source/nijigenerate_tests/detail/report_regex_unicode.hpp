// Source decompressFrom and DecompressedIntervals use successive half-open
// intervals, with each start relative to the preceding interval's end.
inline std::uint32_t readDelta(std::span<const std::uint8_t> data, std::size_t& index) {
    if (index >= data.size()) throw nijigenerate::compat::RangeError();
    const auto first = data[index++];
    if ((first & 0x80) == 0) return first;
    const auto extra = ((first >> 5) & 1) + 1;
    std::uint32_t value = first & 0x1f;
    if (data.size() - index < static_cast<std::size_t>(extra))
        throw nijigenerate::compat::ThrowableException(
            nijigenerate::compat::RetainedString("bad code point interval encoding"));
    for (int j = 0; j < extra; ++j) value = (value << 8) | data[index + j];
    index += extra;
    return value;
}

inline bool contains(std::span<const std::uint8_t> data, std::uint32_t point) {
    std::size_t index = 0;
    std::uint32_t previousEnd = 0;
    while (index != data.size()) {
        const auto first = previousEnd + readDelta(data, index);
        const auto last = index == data.size() ? std::uint32_t{0x110000} : first + readDelta(data, index);
        if (point < first) return false;
        if (point < last) return true;
        previousEnd = last;
    }
    return false;
}

inline bool isDigit(std::uint32_t point) { return contains(Nd, point); }

inline bool isWord(std::uint32_t point) {
    return contains(Alphabetic, point) || contains(Mn, point) || contains(Mc, point) ||
        contains(Me, point) || contains(Nd, point) || contains(Pc, point);
}

template<std::size_t N>
consteval auto propertyBytes(const char (&hex)[N]) {
    static_assert((N - 1) % 2 == 0);
    std::array<std::uint8_t, (N - 1) / 2> bytes{};
    const auto nibble = [](char value) {
        if (value >= '0' && value <= '9') return value - '0';
        if (value >= 'A' && value <= 'F') return value - 'A' + 10;
        throw "Invalid authored Unicode property literal";
    };
    for (std::size_t i = 0; i < bytes.size(); ++i)
        bytes[i] = static_cast<std::uint8_t>((nibble(hex[i * 2]) << 4) | nibble(hex[i * 2 + 1]));
    return bytes;
}

